// Generates web/js/spec.js and vst/src/generated/spec.h from tools/spec.js + tools/wavelets.json.
// Usage: node tools/gen_spec.js
'use strict';
const fs = require('fs');
const path = require('path');
const spec = require('./spec.js');
const wav = JSON.parse(fs.readFileSync(path.join(__dirname, 'wavelets.json'), 'utf8'));

const root = path.join(__dirname, '..');
const { DEVICE, CHORD_H, APP, DEFAULT_PRESET, PARAMS, INDEX, SECTIONS, PRESETS, TOP, CATEGORIES, LFO2_TARGETS, LFO2_ROLE, ROLES, SLOTS, DELAY_BEATS, LFO_BEATS,
  CHORDS, CHORD_KEYS, NEW_FIRST, NEW_COUNT, DESCRIPTIONS, TOUR } = spec;
// the fields of an oscillator, in the order of the C++ SlotDef (a field an oscillator lacks is -1: the subtractive ones have no
// atom pattern, the additive ones no source wave)
const SLOT_FIELDS = ['lvl', 'wavelet', 'wave', 'width', 'sparsity', 'phase', 'pattern', 'seed', 'tilt', 'bar1', 'atk', 'spread', 'body', 'bright', 'sus',
  'ftype', 'fcut', 'fslope', 'fres', 'fkey', 'fenv', 'fvel', 'pcen', 'pwid', 'pdep', 'oct', 'semi', 'fine', 'eon', 'ea', 'ed', 'es', 'er', 'pamt', 'ptime'];
const defaultPresetIndex = PRESETS.findIndex(p => p.name === DEFAULT_PRESET);

const presetValues = PRESETS.map(pr => ({
  name: pr.name,
  cat: pr.cat,
  rank: pr.rank,   // beta 0.5: its place in its category's list (the preset browsers' default order)
  ...(pr.stars ? { stars: pr.stars } : {}),   // beta 0.3: OktoPierre's vote in his listening test (the browsers' marks)
  values: PARAMS.map(p => (pr.v[p.key] !== undefined ? pr.v[p.key] : p.def)),
}));
const wavelets = wav.order.map((n, i) => ({ id: n, name: PARAMS[INDEX.wavelet].choices[i], h: wav.h[n] }));

// ---------------------------------------------------------------- web
const web = {
  DEVICE, CHORD_H, APP, DEFAULT_PRESET: defaultPresetIndex, TOP, NEW_FIRST, NEW_COUNT, DESCRIPTIONS, TOUR, CATEGORIES, PARAMS, SECTIONS, WAVELETS: wavelets,
  PRESETS: presetValues,
  LFO2_TARGETS: LFO2_TARGETS.map(k => INDEX[k]),   // beta 0.3: the parameters LFO 2 can move (lfo2_target order, the parameters of A1)
  ROLES, LFO2_ROLE: LFO2_ROLE.map(r => ROLES.indexOf(r)),   // the role (index in ROLES) of each target: LFO 2 moves it in every oscillator
  SLOTS: SLOTS.map(s => ({ id: s.id, mode: s.mode, name: s.name, k: Object.fromEntries(Object.entries(s.k).map(([f, key]) => [f, INDEX[key]])) })),
  DELAY_BEATS, LFO_BEATS,   // beta 0.6: the note values of the tempo sync in beats (fx_ddiv / lfo_div choice order)
  CHORDS, CHORD_KEYS,   // Okto MultiWave Synth: the chord types (chord_type choice order) and the type of each selector key
};
const webOut = '// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)\n// SPDX-License-Identifier: GPL-3.0-or-later\n// GENERATED by tools/gen_spec.js — do not edit.\n' +
  'var WS_SPEC = ' + JSON.stringify(web, null, 1) + ';\n' +
  "if (typeof module !== 'undefined') module.exports = WS_SPEC;\n";
fs.writeFileSync(path.join(root, 'web', 'js', 'spec.js'), webOut);

// ---------------------------------------------------------------- C++
const CURVES = ['lin', 'exp', 'pow2', 'int', 'choice'];
const FMTS = ['pct', 'db', 'sec', 'hz', 'cents', 'band', 'dbband', 'int', 'choice', 'deg', 'cyc', 'semi', 'bipct', 'bandamt'];
const WTYPES = ['knobL', 'knobM', 'knobS', 'knobT', 'seg', 'step', 'drawbar', 'scope', 'scalogram', 'atom', 'source', 'window',
  'adsr', 'leds', 'fxheads', 'keyboard', 'wheels', 'logo', 'presets', 'manual', 'download', 'meter', 'zoom', 'credit', 'menu',
  'toggle', 'label', 'chordpads', 'chordname', 'strumplate', 'evaluate'];
const q = s => JSON.stringify(s); // UTF-8 string literal (JSON escaping is valid C for our content)
const num = v => (Number.isInteger(v) ? v.toFixed(1) : String(v));
const enumName = k => 'P_' + k.toUpperCase();

let h = '';
h += '// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)\n// SPDX-License-Identifier: GPL-3.0-or-later\n// GENERATED by tools/gen_spec.js — do not edit.\n#pragma once\n\nnamespace ws {\n\n';
h += `constexpr float kDeviceW = ${DEVICE.w}.0f, kDeviceH = ${DEVICE.h}.0f, kChordH = ${CHORD_H}.0f;\n`;
h += `inline constexpr const char* kAppName = ${q(APP.name)};\ninline constexpr const char* kAppAuthor = ${q(APP.author)};\n`;
h += `inline constexpr const char* kAppCredit = ${q(APP.credit)};\ninline constexpr const char* kAppVersion = ${q(APP.version)};\n`;
h += `inline constexpr const char* kAppPanelCredit = ${q(APP.panelCredit)};\n`;   // beta 0.7: "By OktoPierre"
h += `inline constexpr const char* kAppVersionNum = ${q(APP.versionNum)};\n`;
h += `inline constexpr const char* kAppCopyright = ${q(APP.copyright)};\ninline constexpr const char* kAppLicense = ${q(APP.license)};\n`;
h += `inline constexpr const char* kAppBase = ${q(APP.base || '')};\n\n`;
h += 'enum ParamId : int {\n' + PARAMS.map((p, i) => `  ${enumName(p.key)} = ${i},`).join('\n') + `\n  kNumParams = ${PARAMS.length}\n};\n\n`;
h += 'enum Curve : int { ' + CURVES.map(c => 'CURVE_' + c.toUpperCase()).join(', ') + ' };\n';
h += 'enum Fmt : int { ' + FMTS.map(c => 'FMT_' + c.toUpperCase()).join(', ') + ' };\n';
h += 'enum WidgetType : int { ' + WTYPES.map(c => 'W_' + c.toUpperCase()).join(', ') + ' };\n\n';
h += `struct ParamDef {
  const char* key; const char* name; const char* shortName;
  int curve; int fmt; double min, max, def; bool hidden; bool structural; bool perf;
  int numChoices; const char* const* choices; const char* const* choiceShort;
};
// style: 1 the engine selector, 2 a knob labelled with its value (note values); vis: the parameter whose state shows it
// (visOn: shown while it is on, else while it is off; -1: always); only: 0 both, 1 web app only, 2 plug-in only;
// text: a toggle's or label's text, a menu's caption (beta 0.6)
struct WidgetDef { int type; int param; float x, y, w, h; int style; int env; int vis; bool visOn; int only; const char* text; };
// view: the oscillator (0..3) whose panel shows it, -1 always; vis / visOn: shown only while that parameter is on / off (-1: always)
struct SectionDef { const char* id; const char* title; float x, y, w, h; int view; int vis; bool visOn; int firstWidget, numWidgets; };
struct PresetDef { const char* name; const char* cat; double v[kNumParams]; };

`;
for (const p of PARAMS) if (p.choices) {
  h += `inline constexpr const char* kCh_${p.key}[] = { ${p.choices.map(q).join(', ')} };\n`;
  h += `inline constexpr const char* kChS_${p.key}[] = { ${p.choiceShort.map(q).join(', ')} };\n`;
}
h += '\ninline constexpr ParamDef kParams[kNumParams] = {\n';
for (const p of PARAMS) {
  const ch = p.choices ? `${p.choices.length}, kCh_${p.key}, kChS_${p.key}` : '0, nullptr, nullptr';
  h += `  { ${q(p.key)}, ${q(p.name)}, ${q(p.short)}, CURVE_${p.curve.toUpperCase()}, FMT_${p.fmt.toUpperCase()}, ` +
    `${num(p.min)}, ${num(p.max)}, ${num(p.def)}, ${p.hidden}, ${p.structural}, ${!!p.perf}, ${ch} },\n`;
}
h += '};\n\n';

const widgets = [];
const sections = [];
for (const s of SECTIONS) {
  const first = widgets.length;
  for (const w of s.widgets) widgets.push(w);
  sections.push(`  { ${q(s.id)}, ${q(s.title)}, ${num(s.x)}f, ${num(s.y)}f, ${num(s.w)}f, ${num(s.h)}f, ${s.view}, ${s.vis ? INDEX[s.vis] : -1}, ${!!s.visOn}, ${first}, ${s.widgets.length} },`);
}
h += 'inline constexpr WidgetDef kWidgets[] = {\n';
for (const w of widgets) {
  const t = WTYPES.indexOf(w.type);
  if (t < 0) throw new Error('unknown widget type ' + w.type);
  const pid = w.param ? INDEX[w.param] : -1;
  const style = w.style === 'engine' ? 1 : w.style === 'value' ? 2 : 0;
  const env = w.env === 'amp' ? 0 : w.env === 'mod' ? 1 : w.env === 'own' ? 2 : -1;   // own: the four parameters from `param`
  const vis = w.vis ? INDEX[w.vis] : -1, only = w.only === 'web' ? 1 : w.only === 'vst' ? 2 : 0;
  h += `  { W_${w.type.toUpperCase()}, ${pid}, ${num(w.x)}f, ${num(w.y)}f, ${num(w.w)}f, ${num(w.h)}f, ${style}, ${env}, ${vis}, ` +
    `${!!w.visOn}, ${only}, ${w.text ? q(w.text) : 'nullptr'} },\n`;
}
h += '};\n';
h += `inline constexpr int kNumWidgets = ${widgets.length};\n\n`;
h += 'inline constexpr SectionDef kSections[] = {\n' + sections.join('\n') + '\n};\n';
h += `inline constexpr int kNumSections = ${sections.length};\n\n`;

h += 'inline constexpr PresetDef kPresets[] = {\n';
for (const pr of presetValues) h += `  { ${q(pr.name)}, ${q(pr.cat)}, { ${pr.values.map(v => num(v)).join(', ')} } },\n`;
h += '};\n';
h += `inline constexpr int kNumPresets = ${presetValues.length};\n`;
h += `inline constexpr int kNumTop = ${TOP};   // beta 0.5: the first presets are TOP Sounds, in their order\n`;
h += `// beta 0.3: OktoPierre's vote of each preset in his listening test (0 = none; a mark in the browser)\n`;
h += `inline constexpr int kPresetStars[] = { ${PRESETS.map(p => p.stars || 0).join(', ')} };\n`;
h += `// beta 0.5: each preset's place in its category's list (the preset browser's default order)\n`;
h += `inline constexpr int kPresetRank[] = { ${PRESETS.map(p => p.rank).join(', ')} };\n`;
h += `// the factory categories, in browser and menu order (after TOP Sounds)\n`;
h += `inline constexpr const char* kCategories[] = { ${CATEGORIES.map(q).join(', ')} };\n`;
h += `inline constexpr int kNumCategories = ${CATEGORIES.length};\n`;
h += `// the presets to evaluate (EVALUATE SOUNDS): the new ones, numbered in their names, from kFirstNew\n`;
h += `inline constexpr int kFirstNew = ${NEW_FIRST}, kNumNew = ${NEW_COUNT};\n`;
h += `inline constexpr int kDefaultPreset = ${defaultPresetIndex};   // ${DEFAULT_PRESET}\n\n`;
h += `// beta 0.6: the note values of the tempo sync in beats (a quarter note = 1), in the order of the fx_ddiv / lfo_div choices\n`;
h += `inline constexpr double kDelayBeats[] = { ${DELAY_BEATS.map(v => v.toPrecision(17)).join(', ')} };\n`;
h += `inline constexpr double kLfoBeats[] = { ${LFO_BEATS.map(v => v.toPrecision(17)).join(', ')} };\n`;
h += `// Okto MultiWave Synth: the chord types (the chord_type choices): label, suffix of the chord name, notes above the root (semitones)\n`;
h += `struct ChordDef { const char* label; const char* suffix; int n; int iv[6]; };\n`;
h += 'inline constexpr ChordDef kChords[] = {\n' + CHORDS.map(c => `  { ${q(c.label)}, ${q(c.suffix)}, ${c.iv.length}, { ${c.iv.concat([0, 0, 0, 0, 0, 0]).slice(0, 6).join(', ')} } },`).join('\n') + '\n};\n';
h += `inline constexpr int kNumChords = ${CHORDS.length}, kMaxChordNotes = 6;\n`;
h += `inline constexpr int kChordKeys[12] = { ${CHORD_KEYS.join(', ')} };   // the chord type of each key of the selector octave, C to B\n`;
h += `// beta 0.3: the parameters LFO 2 can move, in the order of the lfo2_target choices (the parameters of A1; kLfo2Role: the role of\n// each target, a column of kSlotRole)\n`;
h += `inline constexpr int kLfo2Targets[] = { ${LFO2_TARGETS.map(k => `P_${k.toUpperCase()}`).join(', ')} };\n`;
h += `inline constexpr int kLfo2Role[] = { ${LFO2_ROLE.map(r => ROLES.indexOf(r)).join(', ')} };\n`;
h += `// Okto MultiWave Synth: the four oscillators A1 A2 B1 B2 (mode 0 subtractive, 1 additive) and the parameter of each field (-1: none);\n// kSlotRole[slot][role]: the parameter of an oscillator that LFO 2 moves for each role (cutoff, slope, resonance, key tracking,\n// envelope amount, velocity amount, position, window width, window depth, source phase)\n`;
h += `struct SlotDef { int mode; ${SLOT_FIELDS.map(f => 'int ' + f).join('; ')}; };\n`;
h += 'inline constexpr SlotDef kSlots[4] = {\n' + SLOTS.map(s => `  { ${s.mode}, ${SLOT_FIELDS.map(f => (s.k[f] ? 'P_' + s.k[f].toUpperCase() : '-1')).join(', ')} },`).join('\n') + '\n};\n';
h += 'inline constexpr int kSlotRole[4][10] = {\n' + SLOTS.map(s => `  { ${ROLES.map(r => (s.k[r] ? 'P_' + s.k[r].toUpperCase() : '-1')).join(', ')} },`).join('\n') + '\n};\n\n';

const maxLen = Math.max(...wavelets.map(w => w.h.length));
h += `inline constexpr int kNumWavelets = ${wavelets.length};\ninline constexpr int kMaxWaveletLen = ${maxLen};\n`;
h += `inline constexpr int kWaveletLen[kNumWavelets] = { ${wavelets.map(w => w.h.length).join(', ')} };\n`;
h += 'inline constexpr double kWaveletH[kNumWavelets][kMaxWaveletLen] = {\n';
for (const w of wavelets) h += `  { ${w.h.map(v => v.toPrecision(17)).join(', ')} },\n`;
h += '};\n\n} // namespace ws\n';

fs.mkdirSync(path.join(root, 'vst', 'src', 'generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'vst', 'src', 'generated', 'spec.h'), h);

// ---------------------------------------------------------------- C++: the listening test (EVALUATE SOUNDS)
// The passage every new preset plays (the same as web/js/evaluate.js: 5 s of the default demo from 12.9 s, notes cut at the end,
// starting on its first note) as sorted note events, and the description of every preset ('' when none).
{
  const vm = require('vm');
  const sandbox = {};
  vm.runInNewContext(fs.readFileSync(path.join(root, 'web', 'js', 'demo_data.js'), 'utf8') + ';this.songs = WS_DEMO_SONGS;', sandbox);
  const song = sandbox.songs[0], START = 12.9, LEN = 5, notes = [];
  for (let i = 0; i < song.notes.length; i += 4) {
    const t = song.notes[i];
    if (t < START || t >= START + LEN) continue;
    notes.push([t - START, Math.min(song.notes[i + 1], START + LEN - t), song.notes[i + 2], song.notes[i + 3]]);
  }
  const t0 = notes[0][0], ev = [];
  for (const [t, d, n, v] of notes) ev.push([t - t0, n, v], [t - t0 + d, n, 0]);
  ev.sort((a, b) => a[0] - b[0] || (a[2] > 0) - (b[2] > 0));   // note-offs before note-ons at the same time
  let v = '// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)\n// SPDX-License-Identifier: GPL-3.0-or-later\n' +
    '// GENERATED by tools/gen_spec.js — do not edit.\n// EVALUATE SOUNDS: the listening passage (Beethoven, Appassionata III, ' +
    'from the demo data: public domain, Mutopia Project) and the descriptions of the presets.\n#pragma once\n\nnamespace ws {\n\n';
  v += 'struct VoteEv { double t; int note; float vel; };   // seconds from the first note; vel 0 = note off\n';
  v += 'inline constexpr VoteEv kVotePassage[] = {\n' + ev.map(e => `  { ${e[0].toFixed(6)}, ${e[1]}, ${num(e[2])}f },`).join('\n') + '\n};\n';
  v += `inline constexpr int kVotePassageN = ${ev.length};\n`;
  v += `inline constexpr double kVotePassageLen = ${Math.max(...ev.map(e => e[0])).toFixed(6)};   // seconds\n\n`;
  v += 'inline constexpr const char* kPresetDesc[] = {\n' + presetValues.map(p => '  ' + q(DESCRIPTIONS[p.name] || '') + ',').join('\n') + '\n};\n\n} // namespace ws\n';
  fs.writeFileSync(path.join(root, 'vst', 'src', 'generated', 'vote_data.h'), v);
}
console.log(`generated: ${PARAMS.length} params, ${widgets.length} widgets, ${sections.length} sections, ${presetValues.length} presets, ${wavelets.length} wavelets`);
